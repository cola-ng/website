CREATE TABLE IF NOT EXISTS amigo_devices (
    id UUID PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES base_users(id) ON DELETE CASCADE,
    name VARCHAR(80) NOT NULL,
    token_hash VARCHAR(64) NOT NULL UNIQUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    revoked_at TIMESTAMPTZ,
    lease_id UUID,
    lease_until TIMESTAMPTZ,
    last_seen_at TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS amigo_devices_owner ON amigo_devices(user_id);

CREATE TABLE IF NOT EXISTS amigo_profiles (
    user_id BIGINT PRIMARY KEY REFERENCES base_users(id) ON DELETE CASCADE,
    state JSONB NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Deduplication survives reconnects and restarts; event IDs are generated by
-- the server, never accepted as an authority/ownership claim from the device.
CREATE TABLE IF NOT EXISTS amigo_events (
    id UUID PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES base_users(id) ON DELETE CASCADE,
    device_id UUID NOT NULL REFERENCES amigo_devices(id) ON DELETE CASCADE,
    kind VARCHAR(24) NOT NULL,
    content JSONB NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS amigo_events_owner_time ON amigo_events(user_id, created_at DESC);
CREATE TABLE IF NOT EXISTS amigo_ws_tickets (
    token_hash VARCHAR(64) PRIMARY KEY,
    device_id UUID NOT NULL REFERENCES amigo_devices(id) ON DELETE CASCADE,
    expires_at TIMESTAMPTZ NOT NULL DEFAULT (NOW() + INTERVAL '30 seconds')
);
CREATE INDEX IF NOT EXISTS amigo_ws_tickets_expiry ON amigo_ws_tickets(expires_at);

ALTER TABLE amigo_devices ADD COLUMN IF NOT EXISTS board TEXT;
ALTER TABLE amigo_devices ADD COLUMN IF NOT EXISTS configuration JSONB;
ALTER TABLE amigo_devices ADD COLUMN IF NOT EXISTS applied_revision BIGINT;
CREATE TABLE IF NOT EXISTS amigo_device_profiles (device_id UUID PRIMARY KEY REFERENCES amigo_devices(id) ON DELETE CASCADE,state JSONB NOT NULL,updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW());
CREATE INDEX IF NOT EXISTS amigo_events_device_time ON amigo_events(device_id,created_at DESC);
CREATE TABLE IF NOT EXISTS learn_observations (
    id BIGSERIAL PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES base_users(id) ON DELETE CASCADE,
    source VARCHAR(32) NOT NULL,
    redacted_text TEXT NOT NULL,
    topics JSONB NOT NULL DEFAULT '[]'::jsonb,
    screen_fingerprint VARCHAR(64) NOT NULL,
    observed_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_learn_observations_user_time
    ON learn_observations(user_id, observed_at DESC);

CREATE TABLE IF NOT EXISTS learn_person_memories (
    id BIGSERIAL PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES base_users(id) ON DELETE CASCADE,
    memory_type VARCHAR(32) NOT NULL,
    subject VARCHAR(160) NOT NULL,
    summary TEXT NOT NULL,
    confidence REAL NOT NULL DEFAULT 0.5,
    evidence_count INTEGER NOT NULL DEFAULT 1,
    positive_feedback INTEGER NOT NULL DEFAULT 0,
    negative_feedback INTEGER NOT NULL DEFAULT 0,
    first_seen_at TIMESTAMPTZ NOT NULL,
    last_seen_at TIMESTAMPTZ NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT learn_person_memories_user_subject_unique
        UNIQUE (user_id, memory_type, subject)
);

CREATE INDEX IF NOT EXISTS idx_learn_person_memories_user_confidence
    ON learn_person_memories(user_id, is_active, confidence DESC);
